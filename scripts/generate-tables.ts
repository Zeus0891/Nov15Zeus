// scripts/generate-tables.ts
// Generate a single Prisma file from Tables.v2.md lists (Hybrid/Global/Tenant)
// Usage:
//   npx tsx scripts/generate-tables.ts --input ./Tables.v2.md --outFile prisma/schemas/generated/models.generated.prisma --snake
//
// Flags:
//   --input <path>     Path to Tables.v2.md (default: ./Tables.v2.md)
//   --outFile <path>   Single output file (default: prisma/schemas/generated/models.generated.prisma)
//   --snake            Adds @@map("snake_case") per model
//
// Notes:
// - Templates follow enterprise best practices (Nov-2025).
// - Actor relations are not created by default (UUIDs only). Enable them manually for CRITICAL PARENT entities.
// - For BH, generates tenantId + globalId and @@unique([tenantId, globalId]).
// - For BT, generates @@unique([tenantId, id]) and Tenant @ Cascade relation (commented placeholder).
// - For BG, no tenantId; includes basic operational indexes.
//
// Tip: Keep generator/datasource in prisma/schemas/_base.prisma

import * as fs from "node:fs/promises";
import * as path from "node:path";

type Bucket = "HYBRID" | "GLOBAL" | "TENANT";

const argv = process.argv.slice(2);
function getFlag(name: string, def?: string) {
    const i = argv.indexOf(`--${name}`);
    if (i !== -1) return argv[i + 1];
    return def;
}
function hasFlag(name: string) {
    return argv.includes(`--${name}`);
}

const INPUT = getFlag("input", path.join(process.cwd(), "Tables.v2.md"))!;
const OUTFILE =
    getFlag("outFile") ?? path.join(process.cwd(), "prisma/schemas/generated/models.generated.prisma");
const USE_SNAKE = hasFlag("snake");

