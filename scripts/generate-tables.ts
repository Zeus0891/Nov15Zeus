const SECTION_HEADERS = {
    HYBRID: /^##\s*Hybrid Tables/i,
    GLOBAL: /^##\s*Global Tables/i,
    TENANT: /^##\s*Tenant Tables/i,
};

function toSnake(name: string) {
    return name
        .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
        .replace(/[\s-]+/g, "_")
        .toLowerCase();
}

function clean(line: string) {
    return line
        .replace(/^-\s+/, "") // Remove markdown list prefix "- "
        .replace(/^\*\*?table_name:?\*\*?$/i, "")
        .replace(/^[-_]+$/, "")
        .replace(/^\s*\/\/.*$/, "")
        .trim();
}

function isModelName(s: string) {
    if (!s) return false;
    // discard lines that are clearly not identifiers
    if (/^\s*$/i.test(s)) return false;
    if (/^[#<*-]/.test(s)) return false;
    if (/^[-_*]+$/.test(s)) return false;
    // avoid comments, descriptions, or inline notes
    if (s.includes("alias") || s.includes("uso") || s.includes("típicos") || s.includes("Casos")) return false;
    if (s.includes("Integración") || s.includes("URLs") || s.includes("Funcionalidad") || s.includes("Comunicaciones") || s.includes("APIs")) return false;
    if (s.includes("Gestión") || s.includes("Configuración") || s.includes("Modelos") || s.includes("sistema")) return false;
    if (s.includes("Datos") || s.includes("Proyectos") || s.includes("Inventario") || s.includes("Empleados")) return false;
    // simple allowlist: letters, numbers, underscores (Prisma model name)
    return /^[A-Z][A-Za-z0-9_]*$/.test(s);
}

async function parseTablesMd(file: string) {
    const raw = await fs.readFile(file, "utf8");
    const lines = raw.split(/\r?\n/);

    let mode: Bucket | null = null;
    const hybrid = new Set<string>();
    const global = new Set<string>();
    const tenant = new Set<string>();

    for (const rawLine of lines) {
        const line = rawLine.trim();

        if (SECTION_HEADERS.HYBRID.test(line)) {
            mode = "HYBRID";
            continue;
        }
        if (SECTION_HEADERS.GLOBAL.test(line)) {
            mode = "GLOBAL";
            continue;
        }
        if (SECTION_HEADERS.TENANT.test(line)) {
            mode = "TENANT";
            continue;
        }

        const t = clean(line);
        if (!isModelName(t)) continue;

        if (mode === "HYBRID") hybrid.add(t);
        else if (mode === "GLOBAL") global.add(t);
        else if (mode === "TENANT") tenant.add(t);
    }

    // sanity: remove accidental duplicates across buckets, preferring HYBRID > GLOBAL > TENANT
    for (const m of hybrid) {
        global.delete(m);
        tenant.delete(m);
    }
    for (const m of global) {
        tenant.delete(m);
    }

    return { hybrid: [...hybrid].sort(), global: [...global].sort(), tenant: [...tenant].sort() };
}

async function ensureDir(p: string) {
    await fs.mkdir(p, { recursive: true });
}

function renderModel(name: string, bucket: Bucket, snake: boolean) {
    switch (bucket) {
        case "TENANT":
            return templateBT(name, snake);
        case "HYBRID":
            return templateBH(name, snake);
        case "GLOBAL":
            return templateBG(name, snake);
    }
}

async function main() {
    const { hybrid, global, tenant } = await parseTablesMd(INPUT);

    // Prepare single-file content
    const outDir = path.dirname(OUTFILE);
    await ensureDir(outDir);

    const headerMeta = `// Source: ${path.relative(process.cwd(), INPUT)}\n// Generated: ${new Date().toISOString()}\n`;

    const parts: string[] = [];
    parts.push(HEADER + headerMeta);
    if (hybrid.length) {
        parts.push(`// ======================================================\n// BH — Base Hybrid (tenant + global)\n// Count: ${hybrid.length}\n// ======================================================\n`);
        for (const m of hybrid) parts.push(renderModel(m, "HYBRID", USE_SNAKE));
    }
    if (global.length) {
        parts.push(`// ======================================================\n// BG — Base Global (shared masters)\n// Count: ${global.length}\n// ======================================================\n`);
        for (const m of global) parts.push(renderModel(m, "GLOBAL", USE_SNAKE));
    }
    if (tenant.length) {
        parts.push(`// ======================================================\n// BT — Base Tenant (tenant-scoped)\n// Count: ${tenant.length}\n// ======================================================\n`);
        for (const m of tenant) parts.push(renderModel(m, "TENANT", USE_SNAKE));
    }

    const content = parts.join("\n\n") + "\n";
    await fs.writeFile(OUTFILE, content, "utf8");

    console.log("✅ Generation complete (single file).");
    console.log(`   Hybrid (BH): ${hybrid.length}`);
    console.log(`   Global (BG): ${global.length}`);
    console.log(`   Tenant (BT): ${tenant.length}`);
    console.log(`   Output file: ${path.relative(process.cwd(), OUTFILE)}`);
}

main().catch((err) => {
    console.error("❌ Generation failed:", err);
    process.exit(1);
});
